import json

P = 691


def mat_mul(A, B, mod=P):
    return (
        ((A[0][0]*B[0][0] + A[0][1]*B[1][0]) % mod, (A[0][0]*B[0][1] + A[0][1]*B[1][1]) % mod),
        ((A[1][0]*B[0][0] + A[1][1]*B[1][0]) % mod, (A[1][0]*B[0][1] + A[1][1]*B[1][1]) % mod),
    )


def mat_det(A, mod=P):
    return (A[0][0]*A[1][1] - A[0][1]*A[1][0]) % mod


def mat_vec(M, v, mod=P):
    return ((M[0][0]*v[0] + M[0][1]*v[1]) % mod, (M[1][0]*v[0] + M[1][1]*v[1]) % mod)


def canon(v, mod=P):
    if v[0] != 0:
        inv = pow(v[0], mod - 2, mod)
        return (1, (v[1] * inv) % mod)
    else:
        inv = pow(v[1], mod - 2, mod)
        return ((v[0] * inv) % mod, 1)


def build_proj_points(mod=P):
    pts = [canon((x, 1), mod) for x in range(mod)]
    pts.append(canon((1, 0), mod))
    pts = sorted(set(pts))
    return pts


def perm_of_matrix(M, proj_pts, pos):
    return tuple(pos[canon(mat_vec(M, v))] for v in proj_pts)


def perm_compose(p, q):
    return tuple(p[q[i]] for i in range(len(q)))


def perm_inverse(p):
    inv = [0] * len(p)
    for i, x in enumerate(p):
        inv[x] = i
    return tuple(inv)


def group_order_from_perms(gens, n):
    """Order of <gens> (permutations of {0..n-1}) via a Schreier-Sims-style orbit-stabilizer
    chain -- degree-based (bounded by n at each level), NOT full-element enumeration (which
    would be infeasible for a ~3.3e8-element group). This is what GAP's own permutation-group
    Size algorithm does internally; re-implemented here from scratch in pure Python since this
    checker may not import GAP or the search script.

    Standard algorithm: for base point b_1=0, compute orbit O_1 under <gens> and Schreier
    generators for the stabilizer of b_1 (via orbit transversal + Schreier's lemma), giving
    |<gens>| = |O_1| * |Stab(b_1)|. Recurse on Stab(b_1) with generators = the Schreier
    generators, using the next base point (smallest point not yet fixed), until the generating
    set stabilizes everything (order 1). This terminates in at most n levels (base size <= n),
    and each level's orbit/Schreier-generator computation is polynomial in n and the generator
    count (which itself is bounded since Schreier generators number |O_i| * (num gens at that
    level) -- kept practical here since n=692 is small).
    """
    ident = tuple(range(n))
    order = 1
    current_gens = list(gens)
    remaining_points = list(range(n))

    while current_gens and any(g != ident for g in current_gens):
        # pick the first point not fixed by all current gens (or just point 0 among remaining)
        base = None
        for p in remaining_points:
            if any(g[p] != p for g in current_gens):
                base = p
                break
        if base is None:
            break
        remaining_points = [p for p in remaining_points if p != base]

        # orbit of base under current_gens, with transversal (word from base to each orbit point)
        orbit = {base: ident}
        frontier = [base]
        while frontier:
            new_frontier = []
            for x in frontier:
                ux = orbit[x]
                for g in current_gens:
                    y = g[x]
                    if y not in orbit:
                        orbit[y] = perm_compose(g, ux)
                        new_frontier.append(y)
            frontier = new_frontier

        order *= len(orbit)

        # Schreier generators for the stabilizer of base: for each orbit point x with
        # transversal u_x, and each generator g, s = u_{g(x)}^{-1} * g * u_x (stabilizes base)
        schreier_gens = set()
        for x, ux in orbit.items():
            for g in current_gens:
                y = g[x]
                uy = orbit[y]
                uy_inv = perm_inverse(uy)
                s = perm_compose(uy_inv, perm_compose(g, ux))
                if s != ident:
                    schreier_gens.add(s)

        current_gens = list(schreier_gens)

    return order


def mult_group_order(a, b, mod=P):
    """Order of the subgroup of Z/mod^* generated by a,b (small, <=mod-1)."""
    cur = {a % mod, b % mod, 1}
    changed = True
    while changed:
        changed = False
        new_elts = set()
        for x in cur:
            for g in (a, b):
                y = (x * g) % mod
                if y not in cur:
                    new_elts.add(y)
        if new_elts:
            cur |= new_elts
            changed = True
    return len(cur)


